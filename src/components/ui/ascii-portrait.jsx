const GLYPHS = "@%#*+=-:.";
const LIGHT_GLYPHS = ".:·-+ .·- ";
const NOISE_RATIO = 0.3;
const DURATION = 2200;
const TICK = 50;

export function AsciiPortrait({ onDecoded }) {
  const ref = useRef(null);

  useEffect(() => {
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
      onDecoded?.();
      return;
    }

    const el = ref.current;
    let interval;

    const startDecode = () => {
      const chars = ART.split("");
      const rowCount = ART.split("\n").length;

      // each visible glyph settles at its own moment: a loose top-to-bottom
      // sweep with per-character jitter, like a split-flap board resolving.
      // a sparse fraction of the empty space churns faint static that
      // dissolves early, so the portrait emerges from a light haze
      let row = 0;
      const settleAt = chars.map((c) => {
        if (c === "\n") {
          row++;
          return 0;
        }
        if (c === " ") {
          return Math.random() < NOISE_RATIO ? Math.random() * DURATION * 0.4 : 0;
        }
        return (row / rowCount) * DURATION * 0.5 + Math.random() * DURATION * 0.5;
      });

      const start = performance.now();
      let announced = false;

      const renderFrame = () => {
        const elapsed = performance.now() - start;
        // let the hero text start rising while the last glyphs settle
        if (!announced && elapsed >= DURATION * 0.7) {
          announced = true;
          onDecoded?.();
        }
        if (elapsed >= DURATION) {
          el.textContent = ART;
          clearInterval(interval);
          return;
        }
        let out = "";
        for (let i = 0; i < chars.length; i++) {
          const c = chars[i];
          if (c === "\n" || elapsed >= settleAt[i]) {
            out += c;
          } else if (c === " ") {
            out += LIGHT_GLYPHS[(Math.random() * LIGHT_GLYPHS.length) | 0];
          } else {
            out += GLYPHS[(Math.random() * GLYPHS.length) | 0];
          }
        }
        el.textContent = out;
      };

      interval = setInterval(renderFrame, TICK);
      renderFrame();
    };

    // wait until the portrait is actually on screen (e.g. a reload that
    // restores scroll position would otherwise play it off-screen)
    const observer = new IntersectionObserver(([entry]) => {
      if (entry.isIntersecting) {
        observer.disconnect();
        startDecode();
      }
    }, { threshold: 0.25 });

    observer.observe(el);

    return () => {
      observer.disconnect();
      if (interval) clearInterval(interval);
    };
  }, []);

  return (
    <div className="w-full flex justify-center overflow-hidden">
      <pre ref={ref} aria-hidden="true" className="ascii-portrait font-mono shrink-0 select-none text-neutral-600">
        {ART}
      </pre>
    </div>
  );
}
